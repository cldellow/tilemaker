-- Bundles the memo analysis (this directory) into include/memo_analysis_lua.h, as one Lua chunk.
-- Run after changing a file here:   lua src/memo_analysis/embed.lua src/memo_analysis include/memo_analysis_lua.h
local dir, out = arg[1], arg[2]
local function read(name)
	local f = assert(io.open(dir .. "/" .. name, "rb"))
	local s = f:read("*a")
	f:close()
	return s
end

local modules = {
	{ "luacheck.utils", "utils.lua" },
	{ "luacheck.lexer", "lexer.lua" },
	{ "luacheck.parser", "parser.lua" },
	{ "luacheck.decoder", "decoder.lua" },
	{ "memo.analyze", "analyze.lua" },
}
local parts = { "-- Generated by src/memo_analysis/embed.lua: don't edit.\n",
	"local modules, loaded = {}, {}\n",
	"local function require(name)\n\tif loaded[name] == nil then loaded[name] = modules[name]() end\n\treturn loaded[name]\nend\n" }
for _, m in ipairs(modules) do
	parts[#parts + 1] = ("modules[%q] = function()\n"):format(m[1])
	parts[#parts + 1] = read(m[2])
	parts[#parts + 1] = "\nend\n"
end
parts[#parts + 1] = 'return require("memo.analyze")\n'
local bundle = table.concat(parts)
assert(not bundle:find(')memo"', 1, true), "the bundle contains the raw string delimiter")
assert((loadstring or load)(bundle, "=memo_analysis")) -- it compiles

-- Raw string pieces of at most 12000 bytes (MSVC limits a string literal to 16 KB)
local pieces, i = {}, 1
while i <= #bundle do
	local j = math.min(i + 11999, #bundle)
	pieces[#pieces + 1] = 'R"memo(' .. bundle:sub(i, j) .. ')memo"'
	i = j + 1
end
local f = assert(io.open(out, "wb"))
f:write("// Generated by src/memo_analysis/embed.lua from src/memo_analysis/*.lua: don't edit.\n")
f:write("// tilemaker's static analysis of profiles for the way_memo/node_memo settings, and luacheck's\n")
f:write("// Lua parser (MIT, see src/memo_analysis/LICENSE.luacheck).\n")
f:write("#ifndef _MEMO_ANALYSIS_LUA_H\n#define _MEMO_ANALYSIS_LUA_H\n\n")
f:write("static const char *const memoAnalysisLua[] = {\n")
for _, p in ipairs(pieces) do f:write(p, ",\n") end
f:write("nullptr\n};\n\n#endif\n")
f:close()
print(("%s: %d bytes of Lua in %d pieces"):format(out, #bundle, #pieces))
